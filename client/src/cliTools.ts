// "OMNeT++: Install / Uninstall Command-Line Tools": puts opp_lint, opp_neddoc and
// opp_ide_mcp on the user's PATH as small shim scripts that run the bundles shipped in
// this extension's dist/ with VS Code's own runtime (ELECTRON_RUN_AS_NODE=1), so no
// Node.js install is needed. Both the extension directory and the runtime path change
// on updates, so the shims are rewritten on activation whenever either one moved.
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import * as vscode from 'vscode';

const TOOLS = ['opp_lint', 'opp_neddoc', 'opp_ide_mcp'];
const STATE_KEY = 'omnetpp.cliTools';
// Identifies files we wrote, so we never overwrite or delete anything else.
const MARKER = 'Generated by the OMNeT++ VS Code extension';
const isWindows = process.platform === 'win32';

interface InstalledState {
  binDir: string;
  runtime: string;
  distDir: string;
}

function defaultBinDir(): string {
  return isWindows
    ? path.join(process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local'), 'omnetpp', 'bin')
    : path.join(os.homedir(), '.local', 'bin');
}

function shimPath(binDir: string, tool: string): string {
  return path.join(binDir, isWindows ? `${tool}.cmd` : tool);
}

function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

function shimContent(tool: string, runtime: string, script: string): string {
  const stale = `${tool}: the OMNeT++ VS Code extension or VS Code was updated or removed. Run "OMNeT++: Install Command-Line Tools" again.`;
  if (isWindows) {
    return [
      '@echo off',
      `rem ${MARKER}; rewritten when the extension is updated.`,
      'setlocal',
      `if not exist "${script}" (echo ${stale} 1>&2 & exit /b 127)`,
      `if not exist "${runtime}" (echo ${stale} 1>&2 & exit /b 127)`,
      'set ELECTRON_RUN_AS_NODE=1',
      `"${runtime}" "${script}" %*`,
      'exit /b %ERRORLEVEL%',
      '',
    ].join('\r\n');
  }
  return [
    '#!/bin/sh',
    `# ${MARKER}; rewritten when the extension is updated.`,
    `script=${shQuote(script)}`,
    `runtime=${shQuote(runtime)}`,
    `if [ ! -f "$script" ] || [ ! -x "$runtime" ]; then echo ${shQuote(stale)} >&2; exit 127; fi`,
    'ELECTRON_RUN_AS_NODE=1 exec "$runtime" "$script" "$@"',
    '',
  ].join('\n');
}

function isOurs(file: string): boolean {
  try {
    return fs.readFileSync(file, 'utf8').includes(MARKER);
  } catch {
    return false;
  }
}

function writeShims(state: InstalledState, tools: string[]): void {
  fs.mkdirSync(state.binDir, { recursive: true });
  for (const tool of tools) {
    const file = shimPath(state.binDir, tool);
    fs.writeFileSync(file, shimContent(tool, state.runtime, path.join(state.distDir, `${tool}.js`)));
    if (!isWindows) fs.chmodSync(file, 0o755);
  }
}

function isOnPath(dir: string): boolean {
  const norm = (p: string) => {
    const r = path.resolve(p).replace(/[\\/]+$/, '');
    return isWindows ? r.toLowerCase() : r;
  };
  const target = norm(dir);
  return (process.env.PATH ?? '').split(path.delimiter).some((p) => p && norm(p) === target);
}

function currentState(context: vscode.ExtensionContext, binDir: string): InstalledState {
  return { binDir, runtime: process.execPath, distDir: context.asAbsolutePath('dist') };
}

async function install(context: vscode.ExtensionContext): Promise<void> {
  const binDir = defaultBinDir();
  const foreign = TOOLS.map((t) => shimPath(binDir, t)).filter((f) => fs.existsSync(f) && !isOurs(f));
  if (foreign.length) {
    const answer = await vscode.window.showWarningMessage(
      `These files already exist and were not created by this extension:\n${foreign.join('\n')}`,
      { modal: true, detail: 'They may come from the @omnetpp/opp-tools npm package. Overwrite them?' },
      'Overwrite',
    );
    if (answer !== 'Overwrite') return;
  }
  const state = currentState(context, binDir);
  try {
    writeShims(state, TOOLS);
  } catch (e) {
    void vscode.window.showErrorMessage(`OMNeT++: could not install the command-line tools into ${binDir}: ${(e as Error).message}`);
    return;
  }
  await context.globalState.update(STATE_KEY, state);
  const installed = `Installed ${TOOLS.join(', ')} into ${binDir}.`;
  if (isOnPath(binDir)) {
    void vscode.window.showInformationMessage(`OMNeT++: ${installed}`);
    return;
  }
  const copy = 'Copy Folder Path';
  const answer = await vscode.window.showWarningMessage(
    `OMNeT++: ${installed} This folder is not on your PATH yet — add it to use the tools from a shell (open a new terminal afterwards).`,
    copy,
  );
  if (answer === copy) await vscode.env.clipboard.writeText(binDir);
}

async function uninstall(context: vscode.ExtensionContext): Promise<void> {
  const state = context.globalState.get<InstalledState>(STATE_KEY);
  const binDir = state?.binDir ?? defaultBinDir();
  const removed: string[] = [];
  for (const tool of TOOLS) {
    const file = shimPath(binDir, tool);
    if (!isOurs(file)) continue;
    fs.rmSync(file, { force: true });
    removed.push(tool);
  }
  await context.globalState.update(STATE_KEY, undefined);
  void vscode.window.showInformationMessage(
    removed.length
      ? `OMNeT++: removed ${removed.join(', ')} from ${binDir}.`
      : `OMNeT++: no command-line tools installed by this extension were found in ${binDir}.`,
  );
}

/** After an extension or VS Code update the shims point at paths that no longer exist. */
function refreshIfMoved(context: vscode.ExtensionContext): void {
  const state = context.globalState.get<InstalledState>(STATE_KEY);
  if (!state) return;
  const now = currentState(context, state.binDir);
  if (now.runtime === state.runtime && now.distDir === state.distDir) return;
  // Shims the user deleted, or replaced with something else, are left alone.
  const ours = TOOLS.filter((t) => isOurs(shimPath(state.binDir, t)));
  if (!ours.length) {
    void context.globalState.update(STATE_KEY, undefined);
    return;
  }
  try {
    writeShims(now, ours);
    void context.globalState.update(STATE_KEY, now);
  } catch {
    // Leave the stale shims; they print a hint to run the install command again.
  }
}

export function registerCliToolsCommands(context: vscode.ExtensionContext): void {
  context.subscriptions.push(
    vscode.commands.registerCommand('omnetpp.installCliTools', () => install(context)),
    vscode.commands.registerCommand('omnetpp.uninstallCliTools', () => uninstall(context)),
  );
  refreshIfMoved(context);
}
