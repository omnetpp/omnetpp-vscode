// The shim scripts that "OMNeT++: Install Command-Line Tools" puts on the PATH. Each one
// runs a bundle in the extension's dist/ with the editor's own runtime. The shims are
// shared by every editor that has the extension, so a shim can point at an editor or an
// extension copy that is gone; it then exits with 127 and a hint.

/** Identifies files we wrote, so we never overwrite or delete anything else. */
export const SHIM_MARKER = 'Generated by the OMNeT++ VS Code extension';

export function shimFileName(tool: string, platform: NodeJS.Platform): string {
  return platform === 'win32' ? `${tool}.cmd` : tool;
}

function shQuote(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** The hint stays free of parentheses and redirection characters, because cmd.exe echoes
 *  it inside a parenthesized block. */
function staleHint(tool: string): string {
  return (
    `${tool}: the OMNeT++ VS Code extension or the editor that installed this tool was updated or removed. ` +
    `Run "OMNeT++: Install Command-Line Tools" again, or install the tools with "npm install -g @omnetpp/opp-tools".`
  );
}

export function shimContent(tool: string, runtime: string, script: string, platform: NodeJS.Platform): string {
  const stale = staleHint(tool);
  if (platform === 'win32') {
    return [
      '@echo off',
      `rem ${SHIM_MARKER}; rewritten when the extension is updated.`,
      'setlocal',
      `if not exist "${script}" (echo ${stale} 1>&2 & exit /b 127)`,
      `if not exist "${runtime}" (echo ${stale} 1>&2 & exit /b 127)`,
      'set ELECTRON_RUN_AS_NODE=1',
      `"${runtime}" "${script}" %*`,
      'exit /b %ERRORLEVEL%',
      '',
    ].join('\r\n');
  }
  return [
    '#!/bin/sh',
    `# ${SHIM_MARKER}; rewritten when the extension is updated.`,
    `script=${shQuote(script)}`,
    `runtime=${shQuote(runtime)}`,
    `if [ ! -f "$script" ] || [ ! -x "$runtime" ]; then echo ${shQuote(stale)} >&2; exit 127; fi`,
    'ELECTRON_RUN_AS_NODE=1 exec "$runtime" "$script" "$@"',
    '',
  ].join('\n');
}

export function isShim(content: string): boolean {
  return content.includes(SHIM_MARKER);
}

const SH_VALUE = (name: string) => new RegExp(`^${name}='((?:[^']|'\\\\'')*)'\\r?$`, 'm');
const CMD_CHECK = /^if not exist "([^"]*)" \(/gm;

/** The script and runtime a shim runs, as written by any version of shimContent. */
export function shimTargets(content: string): { script: string; runtime: string } | undefined {
  if (!isShim(content)) return undefined;
  const script = SH_VALUE('script').exec(content)?.[1];
  const runtime = SH_VALUE('runtime').exec(content)?.[1];
  if (script !== undefined && runtime !== undefined) {
    const unquote = (s: string) => s.replace(/'\\''/g, "'");
    return { script: unquote(script), runtime: unquote(runtime) };
  }
  const checks = [...content.matchAll(CMD_CHECK)].map((m) => m[1]);
  return checks.length === 2 ? { script: checks[0], runtime: checks[1] } : undefined;
}

/** A shim of ours that can only print the stale hint. Unreadable shims count as broken. */
export function isBrokenShim(content: string, exists: (path: string) => boolean): boolean {
  if (!isShim(content)) return false;
  const targets = shimTargets(content);
  return !targets || !exists(targets.script) || !exists(targets.runtime);
}

export interface ShimTargets {
  script: string;
  runtime: string;
}

/**
 * Whether an editor whose tool runs at `current` rewrites this shim: when it is ours and
 * broken (the editor or extension copy it runs is gone, maybe another editor's), or when
 * it still runs `previous`, this editor's install before an update. A working shim of
 * another editor is left alone, so editors do not take turns rewriting it.
 */
export function needsRepair(content: string, exists: (path: string) => boolean, current: ShimTargets, previous?: ShimTargets): boolean {
  if (!isShim(content)) return false;
  if (isBrokenShim(content, exists)) return true;
  const targets = shimTargets(content);
  const runs = (t?: ShimTargets) => !!t && targets?.script === t.script && targets.runtime === t.runtime;
  return runs(previous) && !runs(current);
}
